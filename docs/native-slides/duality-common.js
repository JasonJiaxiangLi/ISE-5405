function clip(poly,a,b,c) {
  const out=[];
  for(let i=0;i<poly.length;i++){
    const u=poly[i],v=poly[(i+1)%poly.length],fu=a*u[0]+b*u[1]-c,fv=a*v[0]+b*v[1]-c;
    if(fu<=1e-9)out.push(u);
    if((fu<=0)!==(fv<=0)){const t=fu/(fu-fv);out.push([u[0]+t*(v[0]-u[0]),u[1]+t*(v[1]-u[1])]);}
  }
  return out;
}
